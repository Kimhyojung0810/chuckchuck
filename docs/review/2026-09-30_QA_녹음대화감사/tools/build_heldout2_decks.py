def _timed(pairs: list[tuple[int, str]]) -> list[tuple[int, int, int, str]]:
    """(장, 말) → (장, 시작 초, 끝 초, 말). 구간 길이는 말 길이에 비례 (최소 6초), 구간은 빈틈없이 잇는다."""
    out, t = [], 0
    for no, text in pairs:
        dur = max(6, round(len(text) / CHARS_PER_SEC))
        out.append((no, t, t + dur, text))
        t += dur
    return out


