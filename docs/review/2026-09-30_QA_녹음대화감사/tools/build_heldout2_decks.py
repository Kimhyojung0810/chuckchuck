def clova_txt(title: str, script: list[tuple]) -> str:
    """클로바노트 .txt 꼴 — 제목 · 날짜와 길이 · 화자 · (MM:SS 줄 + 문장 줄) 블록. 문장은 한 줄에 하나. (감사 빌더와 같은 꼴)"""
    end = int(script[-1][2])
    head = [title, f"2026.09.30 수 오후 2:{10 + len(title) % 40:02d} ・ {end // 60}분 {end % 60}초", "발표자 1", ""]
    body: list[str] = []
    for _no, t0, _t1, text in script:
        t0 = int(t0)
        body.append(f"{t0 // 60:02d}:{t0 % 60:02d}")
        body.extend(s for s in re.split(r"(?<=[.?!])\s+", text) if s.strip())
        body.append("")
    return "\n".join(head + body) + "\n"


