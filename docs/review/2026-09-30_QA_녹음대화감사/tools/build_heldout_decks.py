def clova_txt(title: str, script: list[tuple]) -> str:
    """클로바노트 .txt 꼴 — 제목 · 날짜와 길이 · 화자 · (MM:SS 줄 + 문장 줄) 블록. 문장은 한 줄에 하나. (감사 빌더와 같은 꼴)"""
    end = int(script[-1][2])
    head = [title, f"2026.09.30 수 오후 2:{10 + len(title) % 40:02d} ・ {end // 60}분 {end % 60}초", "발표자 1", ""]
    body: list[str] = []
    for _no, t0, _t1, text in script:
        t0 = int(t0)
        body.append(f"{t0 // 60:02d}:{t0 % 60:02d}")
        body.extend(s for s in re.split(r"(?<=[.?!])\s+", text) if s.strip())
        body.append("")
    return "\n".join(head + body) + "\n"


def _script_of(rec: dict) -> list[tuple]:
    if rec["script"] is not None:
        return rec["script"]
    src_deck, src_r = rec["reuse"]
    return DECKS[src_deck]["recordings"][src_r]["script"]


def _check(name: str, spec: dict) -> None:
    """truth 의 인용이 자료 · 전사와 글자 그대로 맞는지, 기대값이 심은 것과 맞는지 — 어긋나면 쓰기 전에 멈춘다."""
    lines = {s["slide_no"]: [b["text"] for b in s["blocks"]] for s in spec["doc"]["slides"]}
    for rid, rec in spec["recordings"].items():
        script = _script_of(rec)
        assert [s[0] for s in script] == sorted(lines), (name, rid, "장마다 한 번씩, 순서대로")
        assert all(a[2] == b[1] for a, b in zip(script, script[1:])) and script[0][1] == 0, (name, rid, "구간이 이어진다")
        if rec["script"] is None:
            continue
        said = {no: text for no, _t0, _t1, text in script}
        for p in rec["planted"]:
            where = (name, rid, p["id"])
            assert p["speech_quote"] in said[p["slide"]], where + ("speech_quote",)
            if p["deck_quote"] is not None:
                assert p["deck_quote"] in lines[p["slide"]], where + ("deck_quote",)
            if p["kind"] == "skipped_slide":
                rest = " ".join(t for no, t in said.items() if no != p["slide"])
                assert not any(lab in rest for lab in p["labels_any"]), where + ("건너뛴 장의 내용을 다른 장에서 말했다",)
        for t in rec.get("tricky_correct", []):
            assert t["deck"] in lines[t["slide"]] and t["speech"] in said[t["slide"]], (name, rid, "tricky", t["speech"])
        for f in rec.get("spoken_forms", []):
            assert f["deck"] in " ".join(lines[f["slide"]]) and f["speech"] in said[f["slide"]], (name, rid, "spoken", f)
        kinds = {k: sorted(p["slide"] for p in rec["planted"] if p["kind"] in ks) for k, ks in
                 (("c", ("contradiction_number", "contradiction_direction")), ("s", ("skipped_slide",)))}
        assert rec["expect"]["contradiction_slides"] == kinds["c"], (name, rid, "contradiction_slides")
        assert rec["expect"]["skipped_slides"] == kinds["s"], (name, rid, "skipped_slides")
        assert rec["expect"].get("faults", 0) == len(kinds["c"]) + len(kinds["s"]), (name, rid, "faults")


def main() -> None:
    for name, spec in DECKS.items():
        _check(name, spec)
    for name, spec in DECKS.items():
        d = CORPUS / name
        d.mkdir(parents=True, exist_ok=True)
        (d / "slidedoc.json").write_text(json.dumps(spec["doc"], ensure_ascii=False, indent=1), encoding="utf-8")
        recs = {}
        for rid, rec in spec["recordings"].items():
            script = _script_of(rec)
            fname = "transcript.json" if rid == "r1" else f"transcript_{rid}.json"
            (d / fname).write_text(json.dumps(transcript_of(script), ensure_ascii=False, indent=1), encoding="utf-8")
            (d / f"recording_{rid}.txt").write_text(clova_txt(rec["title"], script), encoding="utf-8")
            recs[rid] = {k: v for k, v in rec.items() if k != "script"} | {
                "transcript_file": fname, "clova_file": f"recording_{rid}.txt",
                "slide_segments_truth": [{"slide_no": s[0], "start_sec": s[1], "end_sec": s[2]} for s in script]
                if rec["script"] is not None else "다른 발표 — 장 대응 없음"}
        truth = {"deck": name, "synthetic": True, "group": GROUP, "context": spec["context"],
                 "holdout": "규칙 튜닝이 끝난 뒤 일반화 측정에만 쓴다 — 튜닝 중에 열어 보지 않는다",
                 "total_slides": len(spec["doc"]["slides"]), "recordings": recs}
        (d / "truth.json").write_text(json.dumps(truth, ensure_ascii=False, indent=1), encoding="utf-8")
        print(f"{name}: {len(spec['doc']['slides'])}장 · 녹음 {len(recs)}벌")


if __name__ == "__main__":
    main()
